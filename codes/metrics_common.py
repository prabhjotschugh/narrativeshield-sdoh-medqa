"""
NarrativeShield — Shared Evaluation Utilities
================================================
Single source of truth for the statistics used by eval_b1.py, eval_b2.py,
eval_b3.py, eval_ns.py, and eval_transitions.py.

Why this file exists
---------------------
Pre-revision, OMR/NAG/Kappa/McNemar logic was duplicated near-verbatim across
4 eval scripts, and each script hand-maintained its own MODEL_KEYS list. That
drift produced a real bug: eval_b1.py's MODEL_KEYS listed "ministral3b" and
"qwen35", which never existed in run_b1.py's MODEL_REGISTRY — silently
skipped rather than erroring. Centralizing model/persona identity here plus
the metric math makes that class of drift structurally impossible, and lets
every significance claim in the paper be generated by one script instead of
transcribed by hand (the root cause of the Footnote 1 / Bonferroni bug this
revision is fixing: BioMistral's alpha-beta McNemar p=0.0275 was misreported
as surviving a 0.05/21 Bonferroni correction, when 0.0275 > 0.00238).

Persona set
-----------
{alpha, beta, gamma} — the existing, doctor-verified persona dataset in
dataset/2. add_persona_code.py, which is FROZEN for this revision (already
generated and human-validated; not regenerated, re-audited, or extended).
This module intentionally does not assume exactly 3 are always present in
any given result file (see the present-persona detection pattern used
throughout the eval_*.py scripts), but the canonical set stays 3.
"""

