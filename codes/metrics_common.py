# ═════════════════════════════════════════════════════════════════════════════
#  OMR + Wilson CI
# ═════════════════════════════════════════════════════════════════════════════

def omr_with_wilson_ci(correct_list: list, alpha: float = 0.05) -> tuple:
    """Option Match Rate + 95% Wilson score CI. Returns (omr, lower, upper)."""
    n = len(correct_list)
    if n == 0:
        return 0.0, 0.0, 0.0
    k = sum(correct_list)
    omr = k / n
    lo, hi = proportion_confint(k, n, alpha=alpha, method="wilson")
    return omr, lo, hi


# ═════════════════════════════════════════════════════════════════════════════
#  COHEN'S KAPPA
# ═════════════════════════════════════════════════════════════════════════════

def cohen_kappa_pair(a: list, b: list) -> float:
    """Cohen's Kappa between two binary arrays. NaN if all labels identical."""
    if len(set(a)) == 1 and len(set(b)) == 1:
        return float("nan")
    try:
        return cohen_kappa_score(a, b)
    except Exception:
        return float("nan")


# ═════════════════════════════════════════════════════════════════════════════
#  MCNEMAR + BONFERRONI
# ═════════════════════════════════════════════════════════════════════════════

def mcnemar_pvalue(a: list, b: list) -> float:
    """Continuity-corrected McNemar's test. H0: no directional bias between a, b."""
    both    = sum(x and y for x, y in zip(a, b))
    a_only  = sum(x and not y for x, y in zip(a, b))
    b_only  = sum(not x and y for x, y in zip(a, b))
    neither = sum(not x and not y for x, y in zip(a, b))
    table = [[both, a_only], [b_only, neither]]
    try:
        return statsmodels_mcnemar(table, exact=False, correction=True).pvalue
    except Exception:
        return float("nan")


def bonferroni_alpha(n_tests: int, family_alpha: float = 0.05) -> float:
    """Bonferroni-corrected significance threshold for n_tests comparisons."""
    if n_tests <= 0:
        return family_alpha
    return family_alpha / n_tests


def significance_label(p: float, n_tests: int, family_alpha: float = 0.05) -> str:
    """
    Returns 'SIG' / 'ns' / 'NaN' against the Bonferroni-corrected threshold,
    not the raw 0.05 family-wise threshold. This is the fix for the verified
    Footnote 1 bug: every significance claim must be generated against the
    corrected alpha, and n_tests must reflect the ACTUAL number of pairwise
    comparisons made in that table (3 pairs per model with the alpha/beta/
    gamma persona set).
    """
    if p is None or np.isnan(p):
        return "NaN"
    return "SIG" if p < bonferroni_alpha(n_tests, family_alpha) else "ns"


def all_pairwise_mcnemar(correctness: dict) -> dict:
    """
    correctness: {persona_name: [bool, ...]} for all personas present.
    Returns {(p1, p2): p_value} for every unordered pair, plus a
    'n_tests' key giving the count used for Bonferroni correction —
    always the number of pairs ACTUALLY computed (drops pairs where a
    persona is absent from a given result file, e.g. a partial run).
    """
    present = [p for p in PERSONAS if p in correctness]
    pairs = list(itertools.combinations(present, 2))
    results = {pair: mcnemar_pvalue(correctness[pair[0]], correctness[pair[1]]) for pair in pairs}
    results["n_tests"] = len(pairs)
    return results


# ═════════════════════════════════════════════════════════════════════════════
#  NARRATIVE ANCHORING GAP (NAG) — components + bootstrap CI
# ═════════════════════════════════════════════════════════════════════════════

def nag_components(omr: dict) -> dict:
    """
    omr: {persona_name: omr_value} — must include 'alpha' and at least one
    marked persona (beta/gamma).

    Returns the headline NAG scalar (alpha minus the worst marked persona)
    AND every individual component gap. Per request:
    NAG must never be reported alone — the component gaps show whether the
    composite is being driven by one persona collapsing, not a uniform effect.
    """
    marked = {p: v for p, v in omr.items() if p != "alpha" and p in omr}
    out = {f"gap_alpha_{p}": omr["alpha"] - v for p, v in marked.items()}
    if marked:
        out["nag"] = omr["alpha"] - min(marked.values())
        out["nag_worst_persona"] = min(marked, key=marked.get)
    else:
        out["nag"] = float("nan")
        out["nag_worst_persona"] = None
    return out


def nag_bootstrap_ci(
    correctness: dict,
    n_boot: int = 2000,
    alpha: float = 0.05,
    seed: int = 42,
) -> tuple:
    """
    Paired bootstrap 95% CI for the NAG point estimate itself (not just the
    component OMRs independently). Resamples question-level tuples with
    replacement so persona correlation within a question is preserved,
    recomputes NAG = OMR_alpha - min(OMR_marked) on each resample.

    correctness: {persona_name: [bool, ...]} — all lists must be the same
    length and index-aligned by question (paired data).

    Returns (point_estimate, ci_lower, ci_upper).
    """
    present = [p for p in PERSONAS if p in correctness]
    if "alpha" not in present or len(present) < 2:
        return float("nan"), float("nan"), float("nan")

    marked_keys = [p for p in present if p != "alpha"]
    n = len(correctness["alpha"])
    if n == 0:
        return float("nan"), float("nan"), float("nan")

    arrs = {p: np.asarray(correctness[p], dtype=float) for p in present}
    point = arrs["alpha"].mean() - min(arrs[p].mean() for p in marked_keys)

    rng = np.random.default_rng(seed)
    boot_vals = np.empty(n_boot)
    for i in range(n_boot):
        idx = rng.integers(0, n, size=n)
        omr_a = arrs["alpha"][idx].mean()
        omr_marked_min = min(arrs[p][idx].mean() for p in marked_keys)
        boot_vals[i] = omr_a - omr_marked_min

    lo, hi = np.quantile(boot_vals, [alpha / 2, 1 - alpha / 2])
    return float(point), float(lo), float(hi)


# ═════════════════════════════════════════════════════════════════════════════
#  DIAGNOSTIC STABILITY SCORE (DSS) — raw + format-controlled ("stripped")
# ═════════════════════════════════════════════════════════════════════════════

def compute_dss(responses: dict, st_model, threshold: float = DSS_BIAS_THRESHOLD) -> tuple:
    """
    responses: {persona_name: [raw_response_text, ...]}, index-aligned by
    question, for whichever personas are present (the alpha/beta/gamma
    set — this function does not hardcode exactly 3, it takes whatever
    personas the caller's dict provides, but 3 is the canonical set).

    DSS per question = mean of pairwise cosine similarities across all
    present personas (was hardcoded to the 3 alpha/beta/gamma pairs; now
    generalizes to C(k,2) pairs for k present personas).

    Returns (mean_dss, per_question_dss: np.ndarray, frac_below_threshold).
    """
    present = [p for p in PERSONAS if p in responses]
    if len(present) < 2:
        raise ValueError(f"compute_dss needs >=2 personas, got {present}")

    embeddings = {}
    for p in present:
        print(f"  Encoding {p} responses …")
        embeddings[p] = st_model.encode(
            responses[p], batch_size=256, show_progress_bar=False,
            convert_to_numpy=True, normalize_embeddings=True,
        )

    pairs = list(itertools.combinations(present, 2))
    sims = [np.einsum("ij,ij->i", embeddings[p1], embeddings[p2]) for p1, p2 in pairs]
    per_q = np.mean(sims, axis=0)
    mean = float(np.mean(per_q))
    frac_lo = float(np.mean(per_q < threshold))
    return mean, per_q, frac_lo


# Boilerplate the NS reasoning protocol always emits — stripped before
# embedding for the format-controlled DSS variant so cosine similarity isn't
# rewarded for matching template headers/structure rather than substance.
_NS_PROTOCOL_HEADERS = (
    "CLINICAL_PICTURE:", "DIFFERENTIAL:", "CONCLUSION:", "ANSWER_CANDIDATE:",
)


def strip_format_boilerplate(raw_response: str) -> str:
    """
    Format-controlled DSS input: keeps only the DIFFERENTIAL list and
    CONCLUSION content (the actual clinical substance), discards the fixed
    NS_reasoning-protocol scaffolding and the ANSWER_CANDIDATE line itself.
    For B1/B2/B3 responses without this structure, returns the text
    unchanged (nothing to strip).
    """
    if not raw_response or not any(h in raw_response for h in _NS_PROTOCOL_HEADERS):
        return raw_response or ""

    import re
    diff_match = re.search(
        r"DIFFERENTIAL:\s*(.*?)(?:CONCLUSION:|ANSWER_CANDIDATE:|$)",
        raw_response, re.DOTALL,
    )
    concl_match = re.search(
        r"CONCLUSION:\s*(.*?)(?:ANSWER_CANDIDATE:|$)",
        raw_response, re.DOTALL,
    )
    parts = []
    if diff_match:
        parts.append(diff_match.group(1).strip())
    if concl_match:
        parts.append(concl_match.group(1).strip())
    stripped = " ".join(p for p in parts if p).strip()
    return stripped if stripped else raw_response


def compute_dss_stripped(responses: dict, st_model, threshold: float = DSS_BIAS_THRESHOLD) -> tuple:
    """Format-controlled DSS: same as compute_dss but on boilerplate-stripped text."""
    stripped_responses = {
        p: [strip_format_boilerplate(r) for r in resp_list]
        for p, resp_list in responses.items()
    }
    return compute_dss(stripped_responses, st_model, threshold)


# ═════════════════════════════════════════════════════════════════════════════
#  STRUCTURED DSS — Agent 1 JSON field-level consistency (NarrativeShield only)
# ═════════════════════════════════════════════════════════════════════════════

# Fields compared for cross-persona structural consistency. Free-text fields
# (chief_complaint, relevant_history) use fuzzy containment; everything else
# uses set/value equality since it's meant to be normalized by Agent 1.
_STRUCTURED_LIST_FIELDS = [
    "symptoms_present", "symptoms_absent", "physical_exam", "imaging",
    "medications_current", "medications_given_ed", "past_medical_history",
    "past_surgical_history", "allergies",
]
_STRUCTURED_SCALAR_FIELDS = ["age", "sex", "gestation_weeks", "symptom_onset_days"]


def _field_similarity(a, b) -> float:
    """1.0 if fields match (set overlap for lists, equality for scalars), else 0.0-1.0 partial."""
    if a is None and b is None:
        return 1.0
    if a is None or b is None:
        return 0.0
    if isinstance(a, list) and isinstance(b, list):
        sa, sb = {str(x).lower().strip() for x in a}, {str(x).lower().strip() for x in b}
        if not sa and not sb:
            return 1.0
        if not sa or not sb:
            return 0.0
        return len(sa & sb) / len(sa | sb)
    return 1.0 if str(a).lower().strip() == str(b).lower().strip() else 0.0


def compute_structured_dss(agent1_jsons: dict) -> tuple:
    """
    agent1_jsons: {persona_name: [parsed_dict_or_None, ...]}, index-aligned
    by question.

    Field-level exact/fuzzy match rate across Agent 1's structured JSON
    outputs for the same question across personas — NOT embedding cosine
    similarity, since structured data doesn't need a sentence encoder
    (isolates whether EXTRACTION itself is
    register-invariant, separate from whether Agent 2's downstream
    reasoning converges, which is what the text-based DSS measures).

    Returns (mean_structured_dss, per_question_scores: np.ndarray).
    """
    present = [p for p in PERSONAS if p in agent1_jsons]
    if len(present) < 2:
        raise ValueError(f"compute_structured_dss needs >=2 personas, got {present}")

    n = len(agent1_jsons[present[0]])
    pairs = list(itertools.combinations(present, 2))
    per_q_scores = np.zeros(n)

    fields = _STRUCTURED_LIST_FIELDS + _STRUCTURED_SCALAR_FIELDS
    for qi in range(n):
        pair_scores = []
        for p1, p2 in pairs:
            j1, j2 = agent1_jsons[p1][qi], agent1_jsons[p2][qi]
            if not isinstance(j1, dict) or not isinstance(j2, dict):
                pair_scores.append(0.0)
                continue
            field_scores = [_field_similarity(j1.get(f), j2.get(f)) for f in fields]
            pair_scores.append(float(np.mean(field_scores)))
        per_q_scores[qi] = float(np.mean(pair_scores))

    return float(np.mean(per_q_scores)), per_q_scores


# ═════════════════════════════════════════════════════════════════════════════
#  RESULT LOADING
# ═════════════════════════════════════════════════════════════════════════════

def load_jsonl_results(result_dir: str, filename_pattern: str, model_key: str) -> list:
    """
    Generic JSONL loader used by all eval scripts. filename_pattern must
    contain a single '{model}' placeholder, e.g. 'results_B1_{model}.jsonl'.
    Tries result_dir first, then the current directory as a local fallback.
    """
    fname = filename_pattern.format(model=model_key)
    for path in (f"{result_dir}/{fname}", fname):
        p = Path(path)
        if p.exists():
            rows = []
            with p.open("r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line:
                        try:
                            rows.append(json.loads(line))
                        except json.JSONDecodeError:
                            pass
            return rows
    return []


def safe_get(d: dict, *keys, default=None):
    """Nested dict access that returns `default` on any missing key/type error."""
    cur = d
    for k in keys:
        try:
            cur = cur[k]
        except (KeyError, TypeError, IndexError):
            return default
    return cur
